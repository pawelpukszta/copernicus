#!/usr/bin/env node
/**
 * Generates design/component-exports.generated.md from the INSTALLED version of
 * react-aria-components.
 *
 * Why this exists: the design canvas may only compose screens from components the
 * library actually ships. A hand-written list drifts from the package within one
 * upgrade; this one cannot, because CI runs it in --check mode and fails on a
 * stale file.
 *
 * Usage:
 *   node scripts/generate-component-inventory.mjs           write the file
 *   node scripts/generate-component-inventory.mjs --check   fail if it is stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const outputPath = resolve(here, '../design/component-exports.generated.md');

const { version } = require('react-aria-components/package.json');
const library = await import('react-aria-components');

// Exported names that are not components: contexts, constants, geometry helpers
// and collection internals. Keeping this list explicit means a new export shows up
// in the generated file instead of being silently dropped.
const NON_COMPONENT =
  /(Context|StateContext|^DEFAULT_SLOT$|^DIRECTORY_DRAG_TYPE$|^Point$|^Rect$|^Size$|^LayoutInfo$|^Layout$|^Token$|^Collection$|^CollectionBuilder$|^DefaultCollectionRenderer$|Provider$)/;

const components = Object.keys(library)
  .filter((name) => /^[A-Z]/.test(name) && !NON_COMPONENT.test(name))
  .sort((a, b) => a.localeCompare(b, 'en'));

const lines = [
  '# React Aria Components: available exports',
  '',
  '<!-- Generated by scripts/generate-component-inventory.mjs. Do not edit by hand. -->',
  '',
  'The design canvas may only compose screens from the components listed here, plus plain',
  'HTML. Anything outside this list means writing roles, focus management and keyboard',
  'handling by hand, which needs an ADR first. See `design/component-inventory.md` for the',
  'policy and for what each group requires from JavaScript.',
  '',
  `- Package: \`react-aria-components@${version}\``,
  `- Component exports: ${components.length}`,
  '',
  '```',
  ...components,
  '```',
  '',
];

const content = lines.join('\n');

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(outputPath, 'utf8');
  } catch {
    console.error(`Missing ${outputPath}. Run: pnpm run design:inventory`);
    process.exit(1);
  }
  if (current !== content) {
    console.error(
      `design/component-exports.generated.md is stale for react-aria-components@${version}.\nRun: pnpm run design:inventory`,
    );
    process.exit(1);
  }
  console.log(`Component inventory is current for react-aria-components@${version}.`);
} else {
  writeFileSync(outputPath, content, 'utf8');
  console.log(`Wrote ${components.length} components for react-aria-components@${version}.`);
}
